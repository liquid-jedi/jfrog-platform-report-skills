import importlib.util
import json
import tempfile
import unittest
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SPEC = importlib.util.spec_from_file_location("sample", ROOT / "scripts" / "generate_sample_data.py")
SAMPLE = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(SAMPLE)
RENDER_SPEC = importlib.util.spec_from_file_location("renderer", ROOT / "scripts" / "render_report.py")
RENDER = importlib.util.module_from_spec(RENDER_SPEC)
RENDER_SPEC.loader.exec_module(RENDER)


class PublicSampleTests(unittest.TestCase):
    def test_sample_is_full_synthetic_schema(self):
        data = SAMPLE.build()
        self.assertEqual(data["schema_version"], "0.3")
        self.assertEqual(data["meta"]["server_id"], "northstar-demo")
        self.assertEqual(set(data["current_ai_security"]["inventory"]), {"mcp_servers", "skills", "plugins", "models"})
        self.assertGreaterEqual(len(data["weekly_trend"]["series"]), 4)
        self.assertTrue(data["executive_summary"]["actions"])

    def test_generator_writes_no_customer_identifiers(self):
        with tempfile.TemporaryDirectory() as directory:
            path = Path(directory) / "data.json"
            path.write_text(json.dumps(SAMPLE.build()), encoding="utf-8")
            text = path.read_text(encoding="utf-8").lower()
            for forbidden in ("solenglatest", "liquidjedi", "avinash", ".jfrog.io"):
                self.assertNotIn(forbidden, text)

    def test_sample_footer_declares_synthetic_provenance(self):
        data = SAMPLE.build()
        template = (ROOT / "assets" / "dashboard.html").read_text(encoding="utf-8")
        rendered = template.replace("<!--REPORT_FOOTER-->", "This is a synthetic demonstration generated by the JFrog Platform Report Skill. No customer environment was queried.")
        self.assertIn("synthetic demonstration", rendered)
        self.assertNotIn("<!--REPORT_FOOTER-->", rendered)


if __name__ == "__main__":
    unittest.main()
